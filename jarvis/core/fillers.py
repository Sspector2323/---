"""Фразы, пока Джарвис думает.

Правило (подсмотрено в adewaskar/jarvis): одна короткая фраза в момент, когда работа началась, — и тишина
до ответа. Никакой болтовни «почти готово… ещё немного…» каждые несколько секунд: это и есть «вода».
Манера — дворецкий: коротко, без восклицаний и суеты; имя — изредка и в конце.
Режим FILLERS=chatty возвращает разговорчивость, FILLERS=off — полную тишину.
"""
import random

TOPICS = [
    (("почт", "письм", "ящик", "gmail", "входящ"), ["Смотрю почту.", "Читаю входящие."]),
    (("notion", "ноушн", "задач", "проект", "в работе", "штаб"), ["Сверяюсь с Notion.", "Поднимаю задачи."]),
    (("репозитор", "github", "гитхаб", "коммит", "код", "ветк"), ["Смотрю репозитории.", "Сверяюсь с GitHub."]),
    (("погод", "дожд", "зонт", "холодно", "тепло"), ["Смотрю прогноз."]),
    (("курс", "доллар", "евро", "валют"), ["Смотрю курсы."]),
    (("напомни", "напоминан"), ["Записываю."]),
    (("pdf", "пдф", "документ", "отчёт", "отчет", "план", "презентац"), ["Составляю документ.", "Готовлю документ."]),
    (("курсор", "cursor", "кодекс", "codex", "claude", "клод"), ["Передаю Claude Code.", "Поручаю Claude Code."]),
    (("посмотри", "камер", "экран", "видишь"), ["Смотрю."]),
    (("найди", "поищи", "загугли", "узнай"), ["Ищу.", "Навожу справки."]),
    (("открой", "запусти", "включи"), ["Открываю.", "Сию минуту."]),
]
START = ["Минуту, {user}.", "Сейчас.", "Смотрю.", "Занимаюсь.", "Секунду."]
LONG = ["Задача долгая. Работаю, {user}.", "Это займёт ещё немного времени."]
WAIT = ["Ещё мгновение.", "Почти готово, {user}.", "Сверяю детали.", "Ещё немного."]
ALL = sorted({p for _, ps in TOPICS for p in ps} | set(START) | set(LONG) | set(WAIT))

_last: dict = {}


def _pick(pool: list[str], key: str) -> str:
    """Без одной и той же фразы дважды подряд — так заготовки не звучат заготовками."""
    choice = random.choice([p for p in pool if p != _last.get(key)] or pool)
    _last[key] = choice
    return choice


def first(command: str, user: str) -> str:
    low = command.lower()
    for keys, phrases in TOPICS:
        if any(k in low for k in keys):
            return _pick(phrases, keys[0]).format(user=user)
    return _pick(START, "start").format(user=user)


def long(user: str) -> str:
    return _pick(LONG, "long").format(user=user)


def waiting(user: str):
    """Для режима chatty: бесконечный поток фраз ожидания без повторов подряд."""
    pool = []
    while True:
        if not pool:
            pool = random.sample(WAIT, len(WAIT))
        yield pool.pop().format(user=user)
