"""Фразы-перебивки: Джарвис не молчит, пока думает. Первая — по теме вопроса, дальше — «дворецкие» остроты."""
import random

TOPICS = [
    (("почт", "письм", "ящик", "gmail"), ["Открываю вашу почту.", "Разбираю входящие.", "Смотрю, кто вам пишет."]),
    (("notion", "ноушн", "задач", "проект", "в работе", "штаб"), ["Сверяюсь с Notion.", "Поднимаю список задач.", "Открываю штаб."]),
    (("репозитор", "github", "гитхаб", "коммит", "код", "ветк"), ["Заглядываю в репозитории.", "Опрашиваю GitHub.", "Смотрю, что нового в коде."]),
    (("погод", "дожд", "зонт", "холодно", "тепло"), ["Сверяюсь с небесной канцелярией.", "Смотрю прогноз."]),
    (("курс", "доллар", "евро", "валют"), ["Смотрю курсы. Центробанк, к счастью, не спит.", "Проверяю курсы валют."]),
    (("напомни", "напоминан"), ["Записываю в ежедневник.", "Ставлю напоминание."]),
    (("курсор", "cursor", "кодекс", "codex", "claude", "клод"), ["Передаю задачу коллегам.", "Зову подкрепление."]),
    (("найди", "поищи", "загугли", "узнай"), ["Ищу.", "Уже ищу, Сабина."]),
    (("открой", "запусти", "включи"), ["Открываю.", "Будет исполнено."]),
]
START = ["Секунду, {user}.", "Уже занимаюсь.", "Будет исполнено, минуту.", "Сейчас посмотрю.", "Принято. Работаю.",
         "Одну минуту, {user}.", "Слушаюсь."]
WAIT = ["Ещё мгновение, собираю данные.", "Почти готово, {user}.", "Задача непростая, но я справлюсь.",
        "Сверяю детали. Предпочитаю точность спешке.", "Терпение — добродетель, как говорят британцы.",
        "Минуточку, навожу лоск.", "Процессоры греются, но держатся.", "Думаю. Это у меня получается лучше всего.",
        "Ещё немного. Хороший ответ стоит пары секунд.", "Почти у цели, {user}."]
ALL = sorted({p for _, ps in TOPICS for p in ps} | set(START) | set(WAIT))


def first(command: str, user: str) -> str:
    low = command.lower()
    for keys, phrases in TOPICS:
        if any(k in low for k in keys):
            return random.choice(phrases).format(user=user)
    return random.choice(START).format(user=user)


def waiting(user: str):
    """Бесконечный поток разных фраз ожидания без повторов подряд."""
    pool = []
    while True:
        if not pool:
            pool = random.sample(WAIT, len(WAIT))
        yield pool.pop().format(user=user)
